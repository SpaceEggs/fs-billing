CREATE OR REPLACE VIEW receivables WITH (security_invoker = true) AS
SELECT e.id AS ledger_entry_id, e.tenant_id, e.amount, e.note, e.created_by, e.created_at,
  CASE WHEN v.id IS NOT NULL THEN 'voided' WHEN s.id IS NOT NULL THEN 'received' ELSE 'pending' END AS status,
  s.received_on, s.confirmed_by,
  s.id AS settlement_id, s.note AS settlement_note,
  latest.id AS latest_settlement_id,
  v.id AS void_id, v.adjustment_ledger_entry_id, v.reason AS void_reason,
  v.voided_by, v.created_at AS voided_at
FROM ledger_entries e
LEFT JOIN LATERAL (
  SELECT s.* FROM receivable_settlements s
  WHERE s.ledger_entry_id = e.id
    AND NOT EXISTS (SELECT FROM receivable_settlement_reversals r WHERE r.settlement_id = s.id)
  ORDER BY s.created_at DESC, s.id DESC LIMIT 1
) s ON true
LEFT JOIN LATERAL (
  SELECT s.id FROM receivable_settlements s WHERE s.ledger_entry_id = e.id
  ORDER BY s.created_at DESC, s.id DESC LIMIT 1
) latest ON true
LEFT JOIN receivable_voids v ON v.ledger_entry_id = e.id
WHERE e.kind = 'credit_recharge';
