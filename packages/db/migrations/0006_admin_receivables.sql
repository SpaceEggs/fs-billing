CREATE FUNCTION receivable_events_stamp_created_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF current_user = 'fs_billing_app' THEN
    IF NEW.created_at IS DISTINCT FROM now() THEN
      RAISE EXCEPTION 'created_at is generated by the database' USING ERRCODE = 'insufficient_privilege';
    END IF;
    -- Transaction start can precede a settlement committed while this transaction waited for its tenant lock.
    NEW.created_at := clock_timestamp();
  END IF;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION receivable_events_stamp_created_at() FROM PUBLIC;
