CREATE FUNCTION receivable_settlements_pending_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT FROM receivable_voids WHERE ledger_entry_id = NEW.ledger_entry_id)
    OR EXISTS (
      SELECT FROM receivable_settlements s
      WHERE s.ledger_entry_id = NEW.ledger_entry_id
        AND NOT EXISTS (SELECT FROM receivable_settlement_reversals r WHERE r.settlement_id = s.id)
    ) THEN
    RAISE EXCEPTION 'credit must be pending before confirmation'
      USING ERRCODE = 'check_violation', CONSTRAINT = 'receivable_settlements_pending';
  END IF;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION receivable_settlements_pending_guard() FROM PUBLIC;
-- The lock trigger sorts before this guard, so even direct INSERTs serialize the state check.
CREATE TRIGGER receivable_settlements_state_guard BEFORE INSERT ON receivable_settlements
  FOR EACH ROW EXECUTE FUNCTION receivable_settlements_pending_guard();
